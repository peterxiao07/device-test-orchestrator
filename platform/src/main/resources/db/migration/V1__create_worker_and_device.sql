CREATE TABLE worker (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        worker_code VARCHAR(100) NOT NULL,
                        base_url VARCHAR(255) NOT NULL,
                        last_heartbeat_at TIMESTAMPTZ,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT uk_worker_code UNIQUE (worker_code)
);

CREATE TABLE device (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        sn VARCHAR(100) NOT NULL,
                        die_id VARCHAR(100),
                        product_type VARCHAR(100) NOT NULL,
                        chip_type VARCHAR(100) NOT NULL,
                        worker_id BIGINT NOT NULL,
                        status VARCHAR(30) NOT NULL DEFAULT 'OFFLINE',
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT uk_device_sn UNIQUE (sn),
                        CONSTRAINT fk_device_worker
                            FOREIGN KEY (worker_id) REFERENCES worker (id),
                        CONSTRAINT ck_device_status
                            CHECK (status IN ('IDLE', 'BUSY', 'ERROR', 'OFFLINE'))
);

CREATE INDEX idx_device_worker_id ON device (worker_id);